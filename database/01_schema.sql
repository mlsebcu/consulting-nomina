-- Motor: PostgreSQL 15+ (Neon)

BEGIN;

CREATE TABLE departamento (
    departamento_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(100) NOT NULL,
    cuenta_contable     VARCHAR(20)  NOT NULL,
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_modificacion  TIMESTAMPTZ,
    creado_por          INTEGER,
    modificado_por      INTEGER,
    eliminado_por       INTEGER,
    fecha_eliminacion   TIMESTAMPTZ
);

CREATE UNIQUE INDEX ux_departamento_nombre ON departamento (nombre) WHERE activo;

CREATE TABLE empleado (
    empleado_id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_empleado               VARCHAR(20)   NOT NULL,
    nombres                       VARCHAR(100)  NOT NULL,
    apellidos                     VARCHAR(100)  NOT NULL,
    dpi                           VARCHAR(13)   NOT NULL,
    nit                           VARCHAR(15),
    fecha_nacimiento              DATE          NOT NULL,
    genero                        VARCHAR(15)   NOT NULL,
    estado_civil                  VARCHAR(20)   NOT NULL,
    direccion                     VARCHAR(250)  NOT NULL,
    telefono_movil                VARCHAR(15)   NOT NULL,
    correo_personal               VARCHAR(100)  NOT NULL,
    correo_corporativo            VARCHAR(100)  NOT NULL,
    contacto_emergencia_nombre    VARCHAR(150)  NOT NULL,
    contacto_emergencia_telefono  VARCHAR(15)   NOT NULL,
    banco                         VARCHAR(100)  NOT NULL,
    tipo_cuenta                   VARCHAR(15)   NOT NULL,
    numero_cuenta                 VARCHAR(30)   NOT NULL,
    fecha_ingreso                 DATE          NOT NULL,
    fecha_baja                    DATE,
    puesto                        VARCHAR(100)  NOT NULL,
    salario_base                  NUMERIC(12,2) NOT NULL CHECK (salario_base > 0),
    dias_laborados                INTEGER       NOT NULL DEFAULT 30 CHECK (dias_laborados BETWEEN 0 AND 31),
    departamento_id               INTEGER       NOT NULL REFERENCES departamento (departamento_id),
    activo                        BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_creacion                TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_modificacion            TIMESTAMPTZ,
    creado_por                    INTEGER,
    modificado_por                INTEGER,
    eliminado_por                 INTEGER,
    fecha_eliminacion             TIMESTAMPTZ,
    CONSTRAINT ck_empleado_genero       CHECK (genero IN ('MASCULINO', 'FEMENINO', 'OTRO')),
    CONSTRAINT ck_empleado_estado_civil CHECK (estado_civil IN ('SOLTERO', 'CASADO', 'DIVORCIADO', 'VIUDO', 'UNION_LIBRE')),
    CONSTRAINT ck_empleado_tipo_cuenta  CHECK (tipo_cuenta IN ('MONETARIA', 'AHORRO')),
    CONSTRAINT ck_empleado_fechas       CHECK (fecha_baja IS NULL OR fecha_baja >= fecha_ingreso)
);

CREATE UNIQUE INDEX ux_empleado_codigo ON empleado (codigo_empleado) WHERE activo;
CREATE UNIQUE INDEX ux_empleado_dpi    ON empleado (dpi) WHERE activo;
CREATE INDEX ix_empleado_departamento  ON empleado (departamento_id);
CREATE INDEX ix_empleado_mes_nacimiento ON empleado ((EXTRACT(MONTH FROM fecha_nacimiento))) WHERE activo;

CREATE TABLE usuario (
    usuario_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash       VARCHAR(200) NOT NULL,
    rol                 VARCHAR(20)  NOT NULL CHECK (rol IN ('ADMIN', 'RRHH')),
    empleado_id         INTEGER REFERENCES empleado (empleado_id),
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_modificacion  TIMESTAMPTZ,
    creado_por          INTEGER,
    modificado_por      INTEGER,
    eliminado_por       INTEGER,
    fecha_eliminacion   TIMESTAMPTZ
);

CREATE TABLE naturaleza_concepto (
    naturaleza_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(15) NOT NULL,
    nombre              VARCHAR(50) NOT NULL,
    afecta_neto         BOOLEAN     NOT NULL DEFAULT TRUE,
    es_provision        BOOLEAN     NOT NULL DEFAULT FALSE,
    orden               INTEGER     NOT NULL DEFAULT 0,
    activo              BOOLEAN     NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_modificacion  TIMESTAMPTZ,
    creado_por          INTEGER,
    modificado_por      INTEGER,
    eliminado_por       INTEGER,
    fecha_eliminacion   TIMESTAMPTZ
);

CREATE UNIQUE INDEX ux_naturaleza_codigo ON naturaleza_concepto (codigo) WHERE activo;

CREATE TABLE concepto (
    concepto_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(20)  NOT NULL,
    nombre              VARCHAR(100) NOT NULL,
    naturaleza_id       INTEGER      NOT NULL REFERENCES naturaleza_concepto (naturaleza_id),
    tipo_calculo        VARCHAR(20)  NOT NULL CHECK (tipo_calculo IN ('FIJO', 'PORCENTAJE', 'FORMULA', 'MANUAL')),
    cuenta_contable     VARCHAR(20),
    orden               INTEGER      NOT NULL DEFAULT 0,
    es_sistema          BOOLEAN      NOT NULL DEFAULT FALSE,
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_modificacion  TIMESTAMPTZ,
    creado_por          INTEGER,
    modificado_por      INTEGER,
    eliminado_por       INTEGER,
    fecha_eliminacion   TIMESTAMPTZ
);

CREATE UNIQUE INDEX ux_concepto_codigo ON concepto (codigo) WHERE activo;
CREATE INDEX ix_concepto_naturaleza ON concepto (naturaleza_id);

CREATE TABLE concepto_regla_fiscal (
    concepto_regla_fiscal_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concepto_id               INTEGER       NOT NULL REFERENCES concepto (concepto_id),
    pais                      VARCHAR(3)    NOT NULL,
    anio                      INTEGER       NOT NULL,
    tipo_impuesto             VARCHAR(10)   NOT NULL CHECK (tipo_impuesto IN ('IGSS', 'ISR')),
    es_gravable               BOOLEAN       NOT NULL DEFAULT FALSE,
    es_base_calculo           BOOLEAN       NOT NULL DEFAULT FALSE,
    porcentaje_exencion       NUMERIC(5,2),
    limite_exencion           NUMERIC(12,2),
    activo                    BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_creacion            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_modificacion        TIMESTAMPTZ,
    creado_por                INTEGER,
    modificado_por            INTEGER,
    eliminado_por             INTEGER,
    fecha_eliminacion         TIMESTAMPTZ
);

CREATE UNIQUE INDEX ux_regla_fiscal ON concepto_regla_fiscal (concepto_id, pais, anio, tipo_impuesto) WHERE activo;

-- Valores legales y operativos por año; el motor de cálculo no contiene constantes de negocio.
CREATE TABLE parametro_nomina (
    parametro_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(40)  NOT NULL,
    descripcion         VARCHAR(200) NOT NULL,
    tipo_dato           VARCHAR(10)  NOT NULL CHECK (tipo_dato IN ('NUMERO', 'TEXTO')),
    valor               VARCHAR(50)  NOT NULL,
    anio                INTEGER      NOT NULL,
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_modificacion  TIMESTAMPTZ,
    creado_por          INTEGER,
    modificado_por      INTEGER,
    eliminado_por       INTEGER,
    fecha_eliminacion   TIMESTAMPTZ,
    CONSTRAINT ck_parametro_numero CHECK (tipo_dato <> 'NUMERO' OR valor ~ '^-?[0-9]+(\.[0-9]+)?$')
);

CREATE UNIQUE INDEX ux_parametro_codigo_anio ON parametro_nomina (codigo, anio) WHERE activo;

CREATE TABLE periodo (
    periodo_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio                INTEGER     NOT NULL,
    mes                 INTEGER     NOT NULL CHECK (mes BETWEEN 1 AND 12),
    quincena            INTEGER     CHECK (quincena IN (1, 2)),
    numero_periodo      INTEGER     NOT NULL,
    tipo_periodo        VARCHAR(10) NOT NULL CHECK (tipo_periodo IN ('MENSUAL', 'QUINCENAL')),
    fecha_inicio        DATE        NOT NULL,
    fecha_fin           DATE        NOT NULL,
    estado              VARCHAR(15) NOT NULL DEFAULT 'ABIERTO' CHECK (estado IN ('ABIERTO', 'EN_REVISION', 'CERRADO')),
    fecha_cierre        TIMESTAMPTZ,
    cerrado_por         INTEGER REFERENCES usuario (usuario_id),
    activo              BOOLEAN     NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_modificacion  TIMESTAMPTZ,
    creado_por          INTEGER,
    modificado_por      INTEGER,
    eliminado_por       INTEGER,
    fecha_eliminacion   TIMESTAMPTZ,
    CONSTRAINT ck_periodo_fechas CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT ck_periodo_quincena CHECK (
        (tipo_periodo = 'QUINCENAL' AND quincena IS NOT NULL) OR
        (tipo_periodo = 'MENSUAL' AND quincena IS NULL)
    )
);

CREATE INDEX ix_periodo_anio_mes ON periodo (anio, mes);
CREATE INDEX ix_periodo_estado   ON periodo (estado) WHERE activo;

-- Entradas variables del período (horas extras, comisiones, descuentos de la asociación, etc.).
CREATE TABLE novedad_nomina (
    novedad_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id         INTEGER       NOT NULL REFERENCES empleado (empleado_id),
    periodo_id          INTEGER       NOT NULL REFERENCES periodo (periodo_id),
    concepto_id         INTEGER       NOT NULL REFERENCES concepto (concepto_id),
    cantidad            NUMERIC(8,2),
    monto               NUMERIC(12,2),
    observacion         VARCHAR(250),
    activo              BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_modificacion  TIMESTAMPTZ,
    creado_por          INTEGER,
    modificado_por      INTEGER,
    eliminado_por       INTEGER,
    fecha_eliminacion   TIMESTAMPTZ,
    CONSTRAINT ck_novedad_valor CHECK (
        (cantidad IS NOT NULL AND cantidad > 0) OR (monto IS NOT NULL AND monto > 0)
    )
);

CREATE INDEX ix_novedad_periodo_empleado ON novedad_nomina (periodo_id, empleado_id) WHERE activo;

CREATE TABLE nomina_empleado (
    nomina_empleado_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id         INTEGER       NOT NULL REFERENCES empleado (empleado_id),
    periodo_id          INTEGER       NOT NULL REFERENCES periodo (periodo_id),
    tipo_nomina         VARCHAR(10)   NOT NULL CHECK (tipo_nomina IN ('ANTICIPO', 'FINMES')),
    dias_laborados      INTEGER       NOT NULL DEFAULT 0,
    total_percepciones  NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_deducciones   NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_provisiones   NUMERIC(12,2) NOT NULL DEFAULT 0,
    anticipo            NUMERIC(12,2) NOT NULL DEFAULT 0,
    liquido             NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado              VARCHAR(10)   NOT NULL DEFAULT 'ABIERTA' CHECK (estado IN ('ABIERTA', 'CERRADA')),
    fecha_calculo       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    activo              BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_modificacion  TIMESTAMPTZ,
    creado_por          INTEGER,
    modificado_por      INTEGER,
    eliminado_por       INTEGER,
    fecha_eliminacion   TIMESTAMPTZ
);

CREATE UNIQUE INDEX ux_nomina_empleado_periodo ON nomina_empleado (empleado_id, periodo_id, tipo_nomina) WHERE activo;
CREATE INDEX ix_nomina_empleado_periodo ON nomina_empleado (periodo_id, tipo_nomina);

CREATE TABLE nomina_detalle (
    nomina_detalle_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nomina_empleado_id  INTEGER       NOT NULL REFERENCES nomina_empleado (nomina_empleado_id) ON DELETE CASCADE,
    concepto_id         INTEGER       NOT NULL REFERENCES concepto (concepto_id),
    concepto_codigo     VARCHAR(20)   NOT NULL,
    concepto_nombre     VARCHAR(100)  NOT NULL,
    naturaleza_codigo   VARCHAR(15)   NOT NULL,
    cantidad            NUMERIC(8,2),
    monto               NUMERIC(12,2) NOT NULL,
    orden               INTEGER       NOT NULL DEFAULT 0,
    activo              BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_modificacion  TIMESTAMPTZ,
    creado_por          INTEGER,
    modificado_por      INTEGER,
    eliminado_por       INTEGER,
    fecha_eliminacion   TIMESTAMPTZ
);

CREATE INDEX ix_nomina_detalle_cabecera ON nomina_detalle (nomina_empleado_id);
CREATE INDEX ix_nomina_detalle_concepto ON nomina_detalle (concepto_codigo);

COMMIT;
